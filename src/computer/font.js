export const LINE_H = 13;
const ROWS = 11;

// Build a white glyph atlas once; tinted copies are cached per colour.
let atlas = null;
const map = new Map();
const tinted = new Map();
function buildAtlas() {
  const chars = Object.keys(GLYPHS);
  const W = chars.reduce((s, c) => s + GLYPHS[c][0] + 2, 0);
  const cv = document.createElement('canvas'); cv.width = W; cv.height = ROWS + 1;
  const ctx = cv.getContext('2d');
  ctx.fillStyle = '#fff';
  let x = 0;
  for (const c of chars) {
    const [w, top, rows] = GLYPHS[c];
    const rr = rows ? rows.split('|') : [];
    rr.forEach((row, ry) => { for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') ctx.fillRect(x + rx, top + ry, 1, 1); });
    map.set(c, { x, w });
    x += w + 2;
  }
  atlas = cv;
}
function tint(color) {
  if (!atlas) buildAtlas();
  if (tinted.has(color)) return tinted.get(color);
  const cv = document.createElement('canvas'); cv.width = atlas.width; cv.height = atlas.height;
  const ctx = cv.getContext('2d');
  ctx.drawImage(atlas, 0, 0);
  ctx.globalCompositeOperation = 'source-in';
  ctx.fillStyle = color; ctx.fillRect(0, 0, cv.width, cv.height);
  tinted.set(color, cv);
  return cv;
}
function glyph(c) {
  if (!atlas) buildAtlas();
  return map.get(c) || map.get('?');
}

export function textWidth(str, bold = false) {
  let w = 0;
  for (const c of str) w += glyph(c).w + 1 + (bold ? 1 : 0);
  return Math.max(0, w - 1);
}

// draw text at (x, y) where y is the top of the line box
export function drawText(ctx, str, x, y, color = '#000', { bold = false, maxW = 0, underline = false } = {}) {
  const img = tint(color);
  let cx = Math.round(x);
  const yy = Math.round(y);
  const limit = maxW ? x + maxW : Infinity;
  let ell = false;
  if (maxW && textWidth(str, bold) > maxW) { ell = true; }
  const ellW = textWidth('...', bold);
  for (const c of str) {
    const g = glyph(c);
    if (ell && cx + g.w + ellW > limit) { drawText(ctx, '...', cx, yy, color, { bold }); break; }
    ctx.drawImage(img, g.x, 0, g.w, ROWS + 1, cx, yy, g.w, ROWS + 1);
    if (bold) ctx.drawImage(img, g.x, 0, g.w, ROWS + 1, cx + 1, yy, g.w, ROWS + 1);
    cx += g.w + 1 + (bold ? 1 : 0);
  }
  if (underline) { ctx.fillStyle = color; ctx.fillRect(Math.round(x), yy + 10, cx - Math.round(x) - 1, 1); }
  return cx - x;
}

// word-wrap into lines no wider than w
export function wrap(str, w, bold = false) {
  const out = [];
  for (const para of String(str).split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const test = line ? line + ' ' + word : word;
      if (textWidth(test, bold) > w && line) { out.push(line); line = word; }
      else line = test;
    }
    out.push(line);
  }
  return out;
}

// scale text: draw at integer scale (for big BIOS/boot text)
export function drawTextScaled(ctx, str, x, y, color, s = 2, bold = false) {
  const img = tint(color);
  let cx = x;
  ctx.imageSmoothingEnabled = false;
  for (const c of str) {
    const g = glyph(c);
    ctx.drawImage(img, g.x, 0, g.w, ROWS + 1, cx, y, g.w * s, (ROWS + 1) * s);
    if (bold) ctx.drawImage(img, g.x, 0, g.w, ROWS + 1, cx + s, y, g.w * s, (ROWS + 1) * s);
    cx += (g.w + 1 + (bold ? 1 : 0)) * s;
  }
  return cx - x;
}
